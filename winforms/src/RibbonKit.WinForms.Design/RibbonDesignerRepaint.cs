namespace RibbonKit.WinForms.Design;

internal sealed record RibbonBackstagePreviewRowState(RibbonItem Item, Rectangle Bounds, bool Selected, bool Hot);
internal sealed record RibbonBackstagePreviewState(Rectangle Bounds, string Text, Rectangle TextBounds, RibbonBackstagePreviewRowState[] Rows)
{
    internal static Rectangle[] Changes(RibbonBackstagePreviewState? before, RibbonBackstagePreviewState? after)
    {
        if (before is null) return after is null ? [] : [after.Bounds];
        if (after is null) return [before.Bounds];
        if (before.Bounds != after.Bounds) return [before.Bounds, after.Bounds];
        var dirty = new List<Rectangle>();
        if (before.Text != after.Text) { dirty.Add(before.TextBounds); dirty.Add(after.TextBounds); }
        for (int i = 0; i < Math.Max(before.Rows.Length, after.Rows.Length); i++)
        {
            var old = i < before.Rows.Length ? before.Rows[i] : null; var current = i < after.Rows.Length ? after.Rows[i] : null;
            if (old == current) continue;
            if (old is not null) dirty.Add(old.Bounds);
            if (current is not null) dirty.Add(current.Bounds);
        }
        return dirty.ToArray();
    }
}

// Keep selection and native invalidation callbacks in one UI-turn repaint.
// The SDK's Invalidate synchronously repaints underlying controls, so callers
// can recognize and ignore invalidations generated by that refresh itself.
internal sealed class RibbonDesignerRepaint(Action<Action> post, Action<Region> invalidate) : IDisposable
{
    private Region? _pending;
    private bool _queued, _disposed;
    private int _flushDepth;
    internal bool IsFlushing => _flushDepth != 0;
    internal void Request(params Rectangle[] rectangles)
    {
        if (_disposed) return;
        foreach (var rectangle in rectangles.Where(rectangle => rectangle.Width > 0 && rectangle.Height > 0))
        {
            if (_pending is null) { _pending = new Region(); _pending.MakeEmpty(); }
            _pending.Union(rectangle);
        }
        if (_pending is null || _queued) return;
        _queued = true; post(Flush);
    }
    private void Flush()
    {
        if (_disposed) return;
        using var dirty = _pending; _pending = null; _queued = false;
        if (dirty is null) return;
        _flushDepth++;
        try { invalidate(dirty); }
        finally { _flushDepth--; }
    }
    public void Dispose() { _disposed = true; _pending?.Dispose(); _pending = null; }
}
